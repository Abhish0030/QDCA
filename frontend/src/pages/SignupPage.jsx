import { useEffect, useState } from 'react';
import { Link, useLocation, useNavigate } from 'react-router-dom';
import { motion } from 'framer-motion';
import { Mail, Lock, Eye, EyeOff, User, Loader2 } from 'lucide-react';
import AuthIllustration from '../components/AuthIllustration.jsx';
import GoogleAuthButton from '../components/GoogleAuthButton.jsx';
import Seo from '../components/Seo.jsx';
import qdcaLogo from '../assets/qdca-logo-new.png';
import { authClient, cacheAuthenticatedSession, waitForAuthenticatedSession } from '../lib/authClient.js';
import { toast } from '../lib/toast.js';
import { trackEvent } from '../lib/monitoring.js';

const authButtonHover = {
  whileHover: { scale: 1.03, y: -2 },
  whileTap: { scale: 0.98 },
  transition: { type: 'spring', stiffness: 420, damping: 18 },
};

function SignupPage() {
  const { pathname, search } = useLocation();
  const navigate = useNavigate();
  const isSignUp = pathname !== '/login';
  const [fullName, setFullName] = useState('');
  const [fullNameError, setFullNameError] = useState('');
  const [email, setEmail] = useState('');
  const [emailError, setEmailError] = useState('');
  const [password, setPassword] = useState('');
  const [passwordError, setPasswordError] = useState('');
  const [isPasswordFocused, setIsPasswordFocused] = useState(false);
  const [confirmPassword, setConfirmPassword] = useState('');
  const [showPassword, setShowPassword] = useState(false);
  const [showConfirmPassword, setShowConfirmPassword] = useState(false);
  const [agreedToTerms, setAgreedToTerms] = useState(false);
  const [termsError, setTermsError] = useState('');
  const [isLoading, setIsLoading] = useState(false);
  const hasUppercase = /[A-Z]/.test(password);
  const hasLowercase = /[a-z]/.test(password);
  const hasNumber = /\d/.test(password);
  const hasSpecialCharacter = /[@#$^&*(),.?:{}|<>]/.test(password);
  // A password is strong if it satisfies all 4 manual rules,
  // OR if it is long (≥12 chars) with uppercase + lowercase + number
  // — this covers passwords generated by Google Password Manager.
  const isPasswordStrong =
    (hasUppercase && hasLowercase && hasNumber && hasSpecialCharacter) ||
    (password.length >= 12 && hasUppercase && hasLowercase && hasNumber);
  const shouldShowPasswordRules = isSignUp && (isPasswordFocused || password) && !isPasswordStrong;
  const confirmPasswordError = isSignUp && confirmPassword && confirmPassword !== password;

  useEffect(() => {
    const searchParams = new URLSearchParams(search);
    const oauthError = searchParams.get('oauthError') || searchParams.get('error');

    if (!oauthError) {
      return;
    }

    const message =
      oauthError === 'state_mismatch'
        ? 'Google sign-in could not be completed because the auth session expired or was blocked. Please try again.'
        : 'Google sign-in could not be completed. Please try again.';

    toast.error(message);
  }, [search]);

  const getEmailError = (value) => {
    const trimmedEmail = value.trim().toLowerCase();
    const emailPattern = /^[^\s@]+@[^\s@]+\.[^\s@]+$/;
    const commonGmailTypos = new Set([
      'gamil.com', 'gmial.com', 'gmai.com', 'gmail.co', 'gmail.con',
      'gmail.cm', 'gnail.com', 'gmal.com', 'googlemail.co',
    ]);
    const domain = trimmedEmail.split('@')[1];

    if (!trimmedEmail) return 'Email address is required.';
    if (!emailPattern.test(trimmedEmail))
      return 'Please enter a valid email address, for example name@gmail.com.';
    if (commonGmailTypos.has(domain))
      return 'Did you mean to write @gmail.com? Please check your email address.';
    return '';
  };

  const getFullNameError = (value) => {
    if (!value.trim()) return 'Full Name is required';
    return '';
  };

  const getPasswordError = (value) => {
    const hasRequiredUppercase = /[A-Z]/.test(value);
    const hasRequiredLowercase = /[a-z]/.test(value);
    const hasRequiredNumber = /\d/.test(value);
    const hasRequiredSpecialCharacter = /[@#$^&*(),.?:{}|<>]/.test(value);
    // Accept Google-generated passwords: long (≥12) + upper + lower + number
    const isGoogleStyleStrong =
      value.length >= 12 && hasRequiredUppercase && hasRequiredLowercase && hasRequiredNumber;

    if (
      isSignUp &&
      value &&
      !isGoogleStyleStrong &&
      (!hasRequiredUppercase || !hasRequiredLowercase || !hasRequiredNumber || !hasRequiredSpecialCharacter)
    ) {
      return 'Weak Password';
    }

    return '';
  };

  const switchAuthMode = (nextIsSignUp) => {
    navigate(nextIsSignUp ? '/signup' : '/login');
    setFullNameError('');
    setFullName('');
    setEmailError('');
    setTermsError('');
    setPassword('');
    setPasswordError('');
    setConfirmPassword('');
    setIsPasswordFocused(false);
    setShowPassword(false);
    setShowConfirmPassword(false);
  };

  const handleEmailChange = (event) => {
    setEmail(event.target.value);
    if (emailError) setEmailError(getEmailError(event.target.value));
  };

  const handleEmailBlur = () => setEmailError(getEmailError(email));

  const handleFullNameChange = (event) => {
    setFullName(event.target.value);
    if (fullNameError) setFullNameError(getFullNameError(event.target.value));
  };

  const handleFullNameBlur = () => setFullNameError(getFullNameError(fullName));

  const handlePasswordChange = (event) => {
    const nextPassword = event.target.value;
    setPassword(nextPassword);
    if (passwordError) setPasswordError(getPasswordError(nextPassword));
  };

  const handlePasswordBlur = () => {
    setIsPasswordFocused(false);
    setPasswordError(getPasswordError(password));
  };

  const handleSubmit = async (event) => {
    event.preventDefault();
    const nextFullNameError = isSignUp ? getFullNameError(fullName) : '';
    const nextPasswordError = getPasswordError(password);
    const nextEmailError = getEmailError(email);
    setFullNameError(nextFullNameError);
    setPasswordError(nextPasswordError);
    setEmailError(nextEmailError);

    if (nextFullNameError) {
      trackEvent('auth_validation_failed', { mode: 'signup', field: 'fullName' });
      return;
    }

    if (nextPasswordError) {
      trackEvent('auth_validation_failed', { mode: 'signup', field: 'password' });
      return;
    }

    if (nextEmailError) {
      trackEvent('auth_validation_failed', { mode: isSignUp ? 'signup' : 'login', field: 'email' });
      return;
    }

    if (isSignUp && confirmPassword !== password) {
      trackEvent('auth_validation_failed', { mode: 'signup', field: 'confirmPassword' });
      return;
    }

    if (isSignUp && !agreedToTerms) {
      setTermsError('You must agree to the Terms of Service and Privacy Policy to continue.');
      trackEvent('auth_validation_failed', { mode: 'signup', field: 'terms' });
      return;
    }

    setIsLoading(true);
    setTermsError('');

    const normalizedEmail = email.trim().toLowerCase();

    try {
      if (isSignUp) {
        const { error } = await authClient.signUp.email({
          email: normalizedEmail,
          password,
          name: fullName.trim(),
        });

        if (error) {
          throw error;
        }
      } else {
        const { error } = await authClient.signIn.email({
          email: normalizedEmail,
          password,
        });

        if (error) {
          throw error;
        }
      }

      const restoredSession = await waitForAuthenticatedSession({
        attempts: 10,
        delayMs: 250,
        preserveCachedOnError: true,
      });

      if (!restoredSession?.user?.id) {
        throw new Error('Sign-in succeeded, but your session could not be restored. Please try again.');
      }

      cacheAuthenticatedSession(restoredSession);
      trackEvent('auth_submit', { mode: isSignUp ? 'signup' : 'login' });
      navigate('/dashboard', { replace: true });
    } catch (error) {
      const message = error?.message || 'Authentication failed. Please try again.';
      trackEvent('auth_failed', { mode: isSignUp ? 'signup' : 'login', reason: message });

      if (message.toLowerCase().includes('invalid') || message.toLowerCase().includes('credential')) {
        setEmailError('Invalid email or password');
      } else if (message.toLowerCase().includes('exist') || message.toLowerCase().includes('already')) {
        setEmailError('An account with this email already exists');
      } else {
        toast.error(message);
      }
    } finally {
      setIsLoading(false);
    }
  };

  return (
    <div className="min-h-screen flex w-full relative bg-qdca-bg">
      <Seo
        title={isSignUp ? 'Create Account' : 'Sign In'}
        description="Create an account or sign in to classify question difficulty levels with QDCA."
        path={isSignUp ? '/signup' : '/login'}
      />
      {/* Background decorations */}
      <div className="absolute top-0 left-0 w-full h-full pointer-events-none overflow-hidden" aria-hidden="true">
        <div className="absolute -top-20 -left-20 w-96 h-96 bg-[#F3E5D8] rounded-full mix-blend-multiply filter blur-3xl opacity-70"></div>
        <div className="absolute top-40 right-1/4 w-72 h-72 bg-[#F3E5D8] rounded-full mix-blend-multiply filter blur-3xl opacity-60"></div>
        <div className="absolute -bottom-32 left-1/3 w-80 h-80 bg-[#F3E5D8] rounded-full mix-blend-multiply filter blur-3xl opacity-60"></div>
        <div className="absolute top-10 left-10 w-32 h-32 dotted-pattern opacity-50"></div>
        <div className="absolute bottom-10 right-10 w-48 h-48 dotted-pattern opacity-50"></div>
        <svg className="absolute bottom-0 left-0 w-full h-64 text-[#F0E6DD] opacity-50" viewBox="0 0 1440 320" preserveAspectRatio="none">
          <path fill="currentColor" fillOpacity="1" d="M0,288L48,272C96,256,192,224,288,197.3C384,171,480,149,576,165.3C672,181,768,235,864,250.7C960,267,1056,245,1152,224C1248,203,1344,181,1392,170.7L1440,160L1440,320L1392,320C1344,320,1248,320,1152,320C1056,320,960,320,864,320C768,320,672,320,576,320C480,320,384,320,288,320C192,320,96,320,48,320L0,320Z"></path>
        </svg>
      </div>

      {/* Left Section */}
      <AuthIllustration panelKey={isSignUp ? 'signup-left-panel' : 'login-left-panel'} />

      {/* Right Section - Auth Card */}
      <div className="w-full lg:w-1/2 flex items-center justify-center min-h-screen py-6 px-4 sm:px-6 relative z-20">
        <div className="bg-white w-full max-w-[520px] rounded-[32px] px-6 py-4 sm:px-8 sm:py-5 glass-shadow relative my-auto">

          {/* Header */}
          <div className="flex flex-col items-center text-center mb-2">
            <div className="flex items-center justify-center gap-0 mb-1.5">
              <img
                src={qdcaLogo}
                alt="QDCA logo"
                className="h-12 sm:h-14 w-auto shrink-0 object-contain -mr-1"
              />
              <span className="text-2xl sm:text-3xl font-extrabold text-qdca-purple tracking-tight">QDCA</span>
            </div>
            <h2 className="text-lg sm:text-xl font-bold text-gray-900 mb-0.5">
              {isSignUp ? 'Create an Account' : 'Welcome Back'}
            </h2>
            <p className="text-xs text-gray-500 font-medium">
              {isSignUp ? 'Join to start classifying questions' : 'Sign in to continue'}
            </p>
          </div>

          {/* Form */}
          <form className="space-y-3" onSubmit={handleSubmit} noValidate>
            {isSignUp && (
              <div>
                <label className="block text-sm font-semibold text-gray-700 mb-1" htmlFor="full-name">Full Name</label>
                <div className="relative">
                  <div className="absolute inset-y-0 left-0 pl-4 flex items-center pointer-events-none">
                    <User size={18} className="text-gray-400" />
                  </div>
                  <input
                    id="full-name"
                    type="text"
                    value={fullName}
                    onChange={handleFullNameChange}
                    onBlur={handleFullNameBlur}
                    autoComplete="name"
                    aria-invalid={fullNameError ? 'true' : 'false'}
                    aria-describedby={fullNameError ? 'full-name-error' : undefined}
                    className={`block w-full pl-11 pr-4 py-2 border rounded-2xl text-gray-900 placeholder-gray-400 focus:outline-none focus:ring-2 focus:border-transparent transition-shadow text-base ${fullNameError ? 'border-red-300 bg-red-50/40 focus:ring-red-400' : 'border-gray-200 focus:ring-qdca-purple'}`}
                    placeholder="Enter your full name"
                  />
                </div>
                {fullNameError && (
                  <p id="full-name-error" className="mt-1.5 text-xs font-medium text-red-600">{fullNameError}</p>
                )}
              </div>
            )}

            <div>
              <label className="block text-sm font-semibold text-gray-700 mb-1" htmlFor="auth-email">Email Address</label>
              <div className="relative">
                <div className="absolute inset-y-0 left-0 pl-4 flex items-center pointer-events-none">
                  <Mail size={18} className="text-gray-400" />
                </div>
                <input
                  id="auth-email"
                  type="email"
                  value={email}
                  onChange={handleEmailChange}
                  onBlur={handleEmailBlur}
                  autoComplete="email"
                  aria-invalid={emailError ? 'true' : 'false'}
                  aria-describedby={emailError ? 'email-error' : undefined}
                  className={`block w-full pl-11 pr-4 py-2 border rounded-2xl text-gray-900 placeholder-gray-400 focus:outline-none focus:ring-2 focus:border-transparent transition-shadow text-base ${emailError ? 'border-red-300 bg-red-50/40 focus:ring-red-400' : 'border-gray-200 focus:ring-qdca-purple'}`}
                  placeholder="Enter your email"
                />
              </div>
              {emailError && (
                <p id="email-error" className="mt-1.5 text-xs font-medium text-red-600">{emailError}</p>
              )}
            </div>

            <div>
              <label className="block text-sm font-semibold text-gray-700 mb-1" htmlFor="auth-password">Password</label>
              <div className="relative">
                <div className="absolute inset-y-0 left-0 pl-4 flex items-center pointer-events-none">
                  <Lock size={18} className="text-gray-400" />
                </div>
                <input
                  id="auth-password"
                  type={showPassword ? 'text' : 'password'}
                  value={password}
                  onChange={handlePasswordChange}
                  onFocus={() => setIsPasswordFocused(true)}
                  onBlur={handlePasswordBlur}
                  autoComplete={isSignUp ? 'new-password' : 'off'}
                  aria-invalid={passwordError ? 'true' : 'false'}
                  aria-describedby={passwordError ? 'password-error' : undefined}
                  className={`block w-full pl-11 pr-11 py-2 border rounded-2xl text-gray-900 placeholder-gray-400 focus:outline-none focus:ring-2 focus:border-transparent transition-shadow text-base ${passwordError ? 'border-red-300 bg-red-50/40 focus:ring-red-400' : 'border-gray-200 focus:ring-qdca-purple'}`}
                  placeholder={isSignUp ? 'Create a password' : 'Enter your password'}
                />
                <button type="button" aria-label={showPassword ? 'Hide password' : 'Show password'} onClick={() => setShowPassword((v) => !v)} className="absolute inset-y-0 right-0 pr-4 flex items-center text-gray-400 hover:text-gray-600 transition-colors">
                  {showPassword ? <EyeOff size={18} /> : <Eye size={18} />}
                </button>
              </div>
              {passwordError && (
                <p id="password-error" className="mt-1.5 text-xs font-semibold text-red-600">{passwordError}</p>
              )}
              {shouldShowPasswordRules && (
                <div className="mt-1.5 space-y-1 text-xs font-semibold">
                  {!password && <p className="text-green-600">Enter strong password</p>}
                  <p className="text-gray-600">Password should contain atleast one capital alphabet and atleast one small alphabet</p>
                  <p className="text-gray-600">Atleast one numeric digit and one special character (@#$^&amp;*(),.?:{}|&lt;&gt;)</p>
                </div>
              )}
            </div>

            {isSignUp ? (
              <>
                <div>
                  <label className="block text-sm font-semibold text-gray-700 mb-1" htmlFor="confirm-password">Confirm Password</label>
                  <div className="relative">
                    <div className="absolute inset-y-0 left-0 pl-4 flex items-center pointer-events-none">
                      <Lock size={18} className="text-gray-400" />
                    </div>
                    <input
                      id="confirm-password"
                      type={showConfirmPassword ? 'text' : 'password'}
                      value={confirmPassword}
                      onChange={(event) => setConfirmPassword(event.target.value)}
                      autoComplete="new-password"
                      aria-invalid={confirmPasswordError ? 'true' : 'false'}
                      aria-describedby={confirmPasswordError ? 'confirm-password-error' : undefined}
                      className={`block w-full pl-11 pr-11 py-2 border rounded-2xl text-gray-900 placeholder-gray-400 focus:outline-none focus:ring-2 focus:border-transparent transition-shadow text-base ${confirmPasswordError ? 'border-red-300 bg-red-50/40 focus:ring-red-400' : 'border-gray-200 focus:ring-qdca-purple'}`}
                      placeholder="Confirm your password"
                    />
                    <button type="button" aria-label={showConfirmPassword ? 'Hide confirm password' : 'Show confirm password'} onClick={() => setShowConfirmPassword((v) => !v)} className="absolute inset-y-0 right-0 pr-4 flex items-center text-gray-400 hover:text-gray-600 transition-colors">
                      {showConfirmPassword ? <EyeOff size={18} /> : <Eye size={18} />}
                    </button>
                  </div>
                  {confirmPasswordError && (
                    <p id="confirm-password-error" className="mt-1.5 text-xs font-semibold text-red-600">
                      It doesn't match with password
                    </p>
                  )}
                </div>

                <div className="pt-0">
                  <label className="flex items-center cursor-pointer">
                      <input
                      id="terms-agreement"
                      type="checkbox"
                      checked={agreedToTerms}
                      onChange={(e) => {
                        setAgreedToTerms(e.target.checked);
                        if (e.target.checked) setTermsError('');
                      }}
                      aria-describedby={termsError ? 'terms-error' : undefined}
                      className="w-4 h-4 rounded border-gray-300 text-qdca-purple focus:ring-qdca-purple"
                    />
                    <span className="ml-3 text-xs font-medium leading-6 text-gray-600">
                      I agree to the{' '}
                      <Link to="/terms" className="font-semibold text-qdca-purple hover:underline">
                        Terms of Service
                      </Link>{' '}
                      and{' '}
                      <Link to="/privacy" className="font-semibold text-qdca-purple hover:underline">
                        Privacy Policy
                      </Link>
                    </span>
                  </label>
                  {termsError && (
                    <p id="terms-error" className="mt-2 text-sm font-medium text-red-600">{termsError}</p>
                  )}
                </div>
              </>
            ) : (
              <div className="flex flex-col gap-3 pt-1 min-[376px]:flex-row min-[376px]:items-center min-[376px]:justify-between">
                <label className="flex items-center cursor-pointer">
                  <input id="remember-me" type="checkbox" className="w-5 h-5 rounded border-gray-300 text-qdca-purple focus:ring-qdca-purple" />
                  <span className="ml-3 text-sm font-medium text-gray-600">Remember me</span>
                </label>
                <Link to="/forgot-password" className="text-sm font-semibold text-qdca-purple hover:underline min-[376px]:text-right">Forgot Password?</Link>
              </div>
            )}

            <motion.button
              type="submit"
              disabled={isLoading}
              className="w-full py-2 px-4 bg-gradient-to-r from-qdca-grad-start to-qdca-grad-end text-white text-lg font-semibold rounded-2xl shadow-lg shadow-purple-900/15 hover:brightness-110 hover:shadow-xl hover:shadow-purple-900/25 transition-[filter,box-shadow] focus:outline-none focus:ring-2 focus:ring-offset-2 focus:ring-qdca-purple disabled:opacity-70 disabled:cursor-not-allowed flex items-center justify-center gap-2"
              {...(!isLoading ? authButtonHover : {})}
            >
              {isLoading ? (
                <>
                  <Loader2 size={20} className="animate-spin" aria-hidden="true" />
                  {isSignUp ? 'Signing up...' : 'Signing in...'}
                </>
              ) : (
                isSignUp ? 'Sign Up' : 'Sign In'
              )}
            </motion.button>
          </form>

          {/* Divider */}
          <div className="mt-3 mb-3 flex items-center gap-4 text-sm text-gray-400 font-medium">
            <div className="h-px flex-1 bg-gray-200"></div>
            <span>OR</span>
            <div className="h-px flex-1 bg-gray-200"></div>
          </div>

          {/* Google Button */}
          <GoogleAuthButton
            label={isSignUp ? 'Sign up with Google' : 'Continue with Google'}
            mode={isSignUp ? 'signup' : 'login'}
            authButtonHover={authButtonHover}
          />

          {/* Footer */}
          <div className="mt-3 text-center text-gray-500 font-medium">
            {isSignUp ? 'Already have an account?' : "Don't have an account?"}{' '}
            <motion.button
              type="button"
              onClick={() => switchAuthMode(!isSignUp)}
              className="text-qdca-purple font-semibold hover:text-[#4A2385] hover:bg-[#F7F1FF] rounded-lg px-2 py-1 transition-colors"
              {...authButtonHover}
            >
              {isSignUp ? 'Sign In' : 'Sign Up'}
            </motion.button>
          </div>

        </div>
      </div>
    </div>
  );
}

export default SignupPage;

